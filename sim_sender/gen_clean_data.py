import pandas as pd
import numpy as np
import os

def generate_smooth_data(output_path, num_rows=500):
    # 原始列名（从hk132.csv获取）
    columns = [
        "消息发生时间", "[消息发布时间][时间_系统RTC]", "[消息发布者ID][功能单元ID]", "[主备状态]", 
        "[数据生成时间][时间_任务时间]", "[数据生成时间1][时间_任务时间]", "[有效性_俯仰角]", 
        "[有效性_横滚角]", "[有效性_真航角]", "[有效性_俯仰角速率]", "[有效性_横滚角速率]", 
        "[有效性_航向角速率]", "[有效性_俯仰角加速度]", "[有效性_横滚角加速度]", "[有效性_航向角加速度]", 
        "[有效性_速度北向]", "[有效性_速度西向]", "[有效性_速度天向]", "[有效性_加速度北向]", 
        "[有效性_加速度西向]", "[有效性_加速度天向]", "[有效性_惯性攻角]", "[有效性_惯性侧滑角]", 
        "[有效性_偏流角]", "[有效性_航迹角]", "[有效性_位置]", "[有效性_惯性气压高度]", "[有效性_地速]", 
        "[载机俯仰角][_角度_毫弧度]", "[载机横滚角][_角度_毫弧度]", "[载机真航角][_角度_毫弧度]", 
        "[载机俯仰角速率][_角速率]", "[载机横滚角速率][_角速率]", "[载机航向角速率][_角速率]", 
        "[载机俯仰角加速度][_角加速度]", "[载机横滚角加速度][_角加速度]", "[载机航向角加速度][_角加速度]", 
        "[载机平台系速度][速度_北向][_速度]", "[载机平台系速度][速度_西向][_速度]", "[载机平台系速度][速度_天向][_速度]", 
        "[载机平台系加速度][加速度_北向][_加速度]", "[载机平台系加速度][加速度_西向][_加速度]", 
        "[载机平台系加速度][加速度_天向][_加速度]", "[载机惯性攻角][_角度_毫弧度]", "[载机侧滑角][_角度_毫弧度]", 
        "[载机偏流角][_角度_毫弧度]", "[载机航迹角][_角度_毫弧度]", "[载机爬升角][_角度_毫弧度]", 
        "[载机位置数据][_纬度]", "[载机位置数据][_经度]", "[载机惯性气压高度][_高度]", 
        "[载机惯性气压参考高度][_高度]", "[载机地速][_速度]"
    ]
    
    data = {}
    dt = 0.2
    t = np.arange(0, num_rows * dt, dt)
    
    # 填充模拟数据
    data["消息发生时间"] = [f"{int(i/5):02d}:{int((i%5)*12):02d}.0" for i in range(num_rows)]
    data["[消息发布时间][时间_系统RTC]"] = 1.74958e12 + t * 1000
    data["[消息发布者ID][功能单元ID]"] = ["FU_025"] * num_rows
    data["[主备状态]"] = [0] * num_rows
    data["[数据生成时间][时间_任务时间]"] = 1.74954e12 + t * 1000
    data["[数据生成时间1][时间_任务时间]"] = 1.74955e12 + t * 1000
    
    # 有效性位全设为1
    valid_cols = [c for c in columns if "有效性" in c]
    for vc in valid_cols:
        data[vc] = [1] * num_rows
        
    # 姿态角（毫弧度）：模拟平稳飞行，微小波动
    data["[载机俯仰角][_角度_毫弧度]"] = 50 + 10 * np.sin(0.1 * t)
    data["[载机横滚角][_角度_毫弧度]"] = 0 + 5 * np.cos(0.05 * t)
    data["[载机真航角][_角度_毫弧度]"] = (1000 + 50 * t) % 6283 # 缓慢转向
    
    # 速率
    data["[载机俯仰角速率][_角速率]"] = 1 * np.cos(0.1 * t)
    data["[载机横滚角速率][_角速率]"] = -0.5 * np.sin(0.05 * t)
    data["[载机航向角速率][_角速率]"] = [50] * num_rows
    
    # 加速度
    for c in columns:
        if "角加速度" in c:
            data[c] = [0.1] * num_rows
            
    # 速度（北，西，天）
    data["[载机平台系速度][速度_北向][_速度]"] = 250 + 2 * t
    data["[载机平台系速度][速度_西向][_速度]"] = -10 - 0.5 * t
    data["[载机平台系速度][速度_天向][_速度]"] = 5 + 0.1 * t
    
    # 加速度（北，西，天）
    data["[载机平台系加速度][加速度_北向][_加速度]"] = [2.0] * num_rows
    data["[载机平台系加速度][加速度_西向][_加速度]"] = [-0.5] * num_rows
    data["[载机平台系加速度][加速度_天向][_加速度]"] = [0.1] * num_rows
    
    # 攻角，侧滑角等
    data["[载机惯性攻角][_角度_毫弧度]"] = [1.5] * num_rows
    data["[载机侧滑角][_角度_毫弧度]"] = [0.2] * num_rows
    data["[载机偏流角][_角度_毫弧度]"] = [3.0] * num_rows
    data["[载机航迹角][_角度_毫弧度]"] = [45.0] * num_rows
    data["[载机爬升角][_角度_毫弧度]"] = [2.5] * num_rows
    
    # 位置（经纬度）：模拟从北京附近起飞
    data["[载机位置数据][_纬度]"] = 39.9 + 0.0001 * t
    data["[载机位置数据][_经度]"] = 116.4 + 0.0001 * t
    
    # 高度
    data["[载机惯性气压高度][_高度]"] = 4000 + 10 * t # 稳定爬升
    data["[载机惯性气压参考高度][_高度]"] = [4000] * num_rows
    data["[载机地速][_速度]"] = np.sqrt((250+2*t)**2 + (-10-0.5*t)**2)
    
    # 检查是否有遗漏的列
    for col in columns:
        if col not in data:
            data[col] = [0.0] * num_rows
            
    df = pd.DataFrame(data, columns=columns)
    df.to_csv(output_path, index=False, encoding='utf-8-sig')
    print(f"模拟数据已生成至: {output_path}")

if __name__ == "__main__":
    out = r"c:\unityproject\unity project\HK132\Assets\data\hk132_clean.csv"
    generate_smooth_data(out)
